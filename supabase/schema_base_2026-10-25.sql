create table public.usuario (
  id_usuario bigint generated by default as identity not null,
  nombre text not null,
  apellido text not null,
  email text not null,
  password_hash text not null,
  rol text not null,
  codigo_acceso text,
  estado boolean default true,
  fecha_registro timestamp with time zone default now(),
  constraint usuario_email_key unique (email),
  constraint usuario_pkey primary key (id_usuario)
);

create table public.sucursal (
  id_sucursal bigint generated by default as identity not null,
  nombre text not null,
  direccion text,
  ciudad text,
  telefono text,
  ventas_online boolean default false,
  estado boolean default true,
  constraint sucursal_pkey primary key (id_sucursal)
);

create table public.empleado (
  id_empleado bigint generated by default as identity not null,
  nombre text not null,
  cargo text not null,
  salario numeric(10,2),
  codigo_empleado text,
  constraint empleado_codigo_empleado_key unique (codigo_empleado),
  constraint empleado_pkey primary key (id_empleado)
);

create table public.producto (
  id_producto bigint generated by default as identity not null,
  nombre text not null,
  descripcion text,
  tipo text,
  precio numeric(10,2) not null,
  estado boolean default true,
  imagen text,
  categoria text,
  tags text,
  rating numeric default 4.5,
  reviews integer default 0,
  long_desc text,
  stock integer not null default 50,
  constraint check_precio_positivo check ((precio >= (0)::numeric)),
  constraint producto_pkey primary key (id_producto)
);

create table public.venta (
  id_venta bigint generated by default as identity not null,
  fecha timestamp with time zone default now(),
  total numeric(10,2) not null default 0,
  tipo_venta text,
  id_empleado bigint,
  id_sucursal bigint,
  id_usuario bigint,
  constraint check_total_positivo check ((total >= (0)::numeric)),
  constraint venta_id_empleado_fkey foreign key (id_empleado) references empleado(id_empleado) on delete set null,
  constraint venta_id_sucursal_fkey foreign key (id_sucursal) references sucursal(id_sucursal) on delete cascade,
  constraint venta_id_usuario_fkey foreign key (id_usuario) references usuario(id_usuario) on delete set null,
  constraint venta_pkey primary key (id_venta),
  constraint venta_tipo_venta_check check ((tipo_venta = any (array['Presencial'::text, 'Online'::text])))
);

create table public.detalle_venta (
  id_detalle_venta bigint generated by default as identity not null,
  cantidad integer not null default 1,
  precio_unitario numeric(10,2) not null,
  id_venta bigint,
  id_producto bigint,
  constraint detalle_venta_id_producto_fkey foreign key (id_producto) references producto(id_producto) on delete restrict,
  constraint detalle_venta_id_venta_fkey foreign key (id_venta) references venta(id_venta) on delete cascade,
  constraint detalle_venta_pkey primary key (id_detalle_venta)
);

create table public.inventario (
  id_inventario bigint generated by default as identity not null,
  id_sucursal bigint,
  id_producto bigint,
  stock_disponible integer not null default 0,
  nivel_minimo integer not null default 0,
  fecha_actualizacion timestamp with time zone default now(),
  constraint check_stock_positivo check ((stock_disponible >= 0)),
  constraint inventario_id_producto_fkey foreign key (id_producto) references producto(id_producto) on delete cascade,
  constraint inventario_id_sucursal_fkey foreign key (id_sucursal) references sucursal(id_sucursal) on delete cascade,
  constraint inventario_pkey primary key (id_inventario)
);

create table public.super_points (
  id_points bigint generated by default as identity not null,
  puntos_generados integer not null,
  fecha_generacion timestamp with time zone default now(),
  id_venta bigint,
  constraint super_points_id_venta_fkey foreign key (id_venta) references venta(id_venta) on delete cascade,
  constraint super_points_pkey primary key (id_points)
);
